/// Emulate mouse movement to wake the connected computer
pub fn wake_computer() -> Result<()> {
    info!("Performing mouse wake gesture...");
    
    #[cfg(target_os = "espidf")]
    {
        use usbd_hid::descriptor::MouseReport;
        use usb_hid_mouse::{send_mouse_report, poll_usb_device};
        
        info!("Sending USB HID mouse movement to wake computer");
        
        // Create mouse movement reports: move right 1px, then left 1px
        let move_right = MouseReport {
            x: 1,
            y: 0,
            buttons: 0,
            wheel: 0,
            pan: 0,
        };
        
        let move_left = MouseReport {
            x: -1,
            y: 0,
            buttons: 0,
            wheel: 0,
            pan: 0,
        };
        
        // Send mouse movement reports
        send_mouse_report(&move_right)?;
        
        // Poll USB device to process the report
        for _ in 0..10 {
            poll_usb_device()?;
            thread::sleep(Duration::from_millis(1));
        }
        
        // Brief delay between movements
        thread::sleep(Duration::from_millis(10));
        
        send_mouse_report(&move_left)?;
        
        // Poll USB device to process the report
        for _ in 0..10 {
            poll_usb_device()?;
            thread::sleep(Duration::from_millis(1));
        }
        
        info!("USB HID mouse wake gesture completed successfully");
    }
    
    #[cfg(not(target_os = "espidf"))]
    {
        info!("Mock mouse movement: move right 1px, then left 1px");
        thread::sleep(Duration::from_millis(20)); // Simulate the time it takes
    }
    
    Ok(())
}



/// UDP server that listens for wake commands
pub fn udp_server(port: u16, wake_requested: Arc<Mutex<bool>>) -> Result<()> {
    let socket = UdpSocket::bind(format!("0.0.0.0:{}", port))?;
    socket.set_read_timeout(Some(Duration::from_secs(1)))?;
    
    info!("UDP server listening on port {}", port);
    
    let mut buf = [0; 64];
    
    loop {
        match socket.recv_from(&mut buf) {
            Ok((size, src)) => {
                info!("Received {} bytes from {}", size, src);
                
                // Simple wake command - any UDP packet triggers wake
                // In production, you might want to verify the packet content
                let mut wake_flag = wake_requested.lock().unwrap();
                *wake_flag = true;
                info!("Wake requested from {}", src);
            }
            Err(e) if e.kind() == std::io::ErrorKind::WouldBlock => {
                // Timeout, continue loop
                continue;
            }
            Err(e) => {
                warn!("UDP receive error: {}", e);
                thread::sleep(Duration::from_secs(1));
            }
        }
    }
}

fn main() -> Result<()> {
    // Initialize the logger
    #[cfg(target_os = "espidf")]
    {
        esp_idf_sys::link_patches();
        esp_idf_svc::log::EspLogger::initialize_default();
    }
    
    #[cfg(not(target_os = "espidf"))]
    {
        env_logger::init();
    }

    info!("ESP32-S2 Companion starting...");

    // Load embedded configuration
    let config = load_config()?;
    
    // Check if Wi-Fi credentials are configured
    if config.wifi.ssid.is_empty() {
        error!("Wi-Fi SSID not configured!");
        error!("Please ensure config.json has Wi-Fi credentials before building (see config.json.example)");
        return Err(anyhow::anyhow!("Wi-Fi not configured in embedded config"));
    }

    // Initialize USB HID mouse (ESP32-S2 only)
    #[cfg(target_os = "espidf")]
    {
        usb_hid_mouse::init_usb_hid()?;
        info!("USB HID mouse initialized for ESP32-S2");
    }

    // Connect to Wi-Fi
    connect_wifi(&config.wifi)?;

    // Shared flag to signal wake requests
    let wake_requested = Arc::new(Mutex::new(false));
    let wake_requested_clone = wake_requested.clone();

    // Start UDP server in a separate thread
    let udp_port = config.wake.udp_port;
    thread::spawn(move || {
        if let Err(e) = udp_server(udp_port, wake_requested_clone) {
            error!("UDP server error: {}", e);
        }
    });

    info!("ESP32-S2 Companion ready!");
    info!("Listening for wake commands on UDP port {}", config.wake.udp_port);

    // Main loop - check for wake requests and execute them
    loop {
        // Poll USB device (ESP32-S2 only)
        #[cfg(target_os = "espidf")]
        {
            if let Err(e) = usb_hid_mouse::poll_usb_device() {
                warn!("USB polling error: {}", e);
            }
        }
        
        {
            let mut wake_flag = wake_requested.lock().unwrap();
            if *wake_flag {
                if let Err(e) = wake_computer() {
                    error!("Failed to wake computer: {}", e);
                } else {
                    info!("Computer wake completed");
                }
                *wake_flag = false;
            }
        }
        
        thread::sleep(Duration::from_millis(100));
    }
}

