/// Configuration structure for the ESP32-S2 companion
#[derive(Debug, Deserialize, Serialize)]
pub struct Config {
    pub wifi: WifiConfig,
    pub wake: WakeConfig,
}

#[derive(Debug, Deserialize, Serialize)]
pub struct WifiConfig {
    pub ssid: String,
    pub password: String,
}

#[derive(Debug, Deserialize, Serialize)]
pub struct WakeConfig {
    pub udp_port: u16,
}

impl Default for Config {
    fn default() -> Self {
        Self {
            wifi: WifiConfig {
                ssid: "".to_string(),
                password: "".to_string(),
            },
            wake: WakeConfig {
                udp_port: 9999,
            },
        }
    }
}

/// Load configuration from embedded build-time constants
pub fn load_config() -> Result<Config> {
    let embedded = get_embedded_config();
    
    info!("Loading embedded configuration");
    
    let config = Config {
        wifi: WifiConfig {
            ssid: embedded.wifi_ssid.to_string(),
            password: embedded.wifi_password.to_string(),
        },
        wake: WakeConfig {
            udp_port: embedded.udp_port,
        },
    };
    
    if config.wifi.ssid.is_empty() {
        warn!("Wi-Fi SSID is empty in embedded config");
    } else {
        info!("Loaded embedded configuration with SSID: {}", config.wifi.ssid);
    }
    
    Ok(config)
}

/// Connect to Wi-Fi using the provided configuration
#[cfg(target_os = "espidf")]
fn connect_wifi(config: &WifiConfig) -> Result<()> {
    use embedded_svc::wifi::{ClientConfiguration, Configuration, Wifi};
    use esp_idf_svc::{
        eventloop::EspSystemEventLoop,
        hal::prelude::Peripherals,
        wifi::{BlockingWifi, EspWifi},
        netif::EspNetifWait,
    };

    let peripherals = Peripherals::take()?;
    let sys_loop = EspSystemEventLoop::take()?;
    let nvs = esp_idf_svc::nvs::EspDefaultNvsPartition::take()?;

    let mut wifi = BlockingWifi::wrap(
        EspWifi::new(peripherals.modem, sys_loop.clone(), Some(nvs))?,
        sys_loop,
    )?;

    let wifi_configuration = Configuration::Client(ClientConfiguration {
        ssid: config.ssid.as_str().into(),
        password: config.password.as_str().into(),
        ..Default::default()
    });

    wifi.set_configuration(&wifi_configuration)?;
    wifi.start()?;
    info!("Starting Wi-Fi...");

    wifi.connect()?;
    info!("Connecting to Wi-Fi...");

    wifi.wait_netif_up()?;
    info!("Wi-Fi connected!");

    let ip_info = wifi.wifi().sta_netif().get_ip_info()?;
    info!("IP info: {:?}", ip_info);

    Ok(())
}

